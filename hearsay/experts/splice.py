"""Splice / discontinuity forensics: traces left where audio was cut, joined, padded or re-quantised.

One continuous microphone recording is continuous in every sense: the background never drops to exact
digital zero, the DC offset of the converter does not step, the noise floor and its spectrum do not change
abruptly in the pauses, the waveform has no sample-level clicks, and the amplitude histogram is smooth.
Each of those properties breaks in a characteristic way when audio is concatenated (unit-selection or
segment-wise TTS, insertion of digital pauses), edited in a DAW, or generated by a vocoder that emits
exact silence. The `discontinuity` expert measures all five and returns the time of every suspected seam
in artifacts["seams_s"] (with a parallel artifacts["seam_types"]) for the report's waveform overlay.

The organizers state the challenge test set has no partially-synthetic clips, so on the test set these
cues act as generic generation artefacts (notably digital-silence padding); on arbitrary user files they
are genuine splice detectors.
"""
from __future__ import annotations

import numpy as np
from scipy import ndimage

from ..evidence import Context, Evidence, Finding, expert
from .environment import ZERO_EPS, finalize, frame_analysis, mono, runs

MIN_ZERO_RUN_S = 0.005        # exact-zero runs shorter than this occur naturally at zero crossings
DC_WIN_S = 0.050              # DC offset measured in adjacent 50 ms windows
DC_JUMP_REL = 0.5             # step in the window mean relative to the windows' AC RMS
DC_JUMP_ABS = 4 / 32768       # ...and at least 4 LSB of 16-bit, so quantisation noise never triggers it
DC_JUMP_ISOLATION = 6.0       # ...and this many times the clip's median window-to-window change (a step, not drift)
PAUSE_DC_REL = 2.0            # DC difference between two long pauses, relative to their background AC level
DC_DRIFT_REL = 0.5            # window-mean wander (re background AC level) reported as sub-audio drift
CLICK_RATIO = 50.0            # |2nd difference| this many local-scale units (natural mouth clicks stay < 50)
CLICK_FLOOR = 2 / 32768       # local-scale floor (2 LSB) so near-silent regions do not explode the ratio
FLOOR_CHANGE_DB = 12.0        # background level change between consecutive long pauses
SPECJUMP_Z = 8.0              # robust z-score of a pause-to-pause spectral distance (background transient)
SPECJUMP_MIN_DB = 6.0         # ...and at least this many dB RMS across bands
SEAM_MERGE_S = 0.05           # seams closer than this are reported once
HIST_COMB_VAR = 4.0           # histogram residual variance (1 = smooth) above which a comb is reported

DEFAULTS = {
    "discontinuity_zero_lead_ms": 0.0, "discontinuity_zero_trail_ms": 0.0,
    "discontinuity_zero_interior_count": 0.0, "discontinuity_zero_interior_ms": 0.0,
    "discontinuity_zero_interior_max_ms": 0.0, "discontinuity_zero_total_frac": 0.0,
    "discontinuity_dc_offset_dbfs": -120.0, "discontinuity_dc_jump_max_rel": 0.0,
    "discontinuity_pause_dc_step_rel": 0.0, "discontinuity_dc_jumps": 0.0,
    "discontinuity_floor_change_max_db": 0.0, "discontinuity_floor_changes": 0.0,
    "discontinuity_click_max_ratio": 0.0, "discontinuity_clicks": 0.0,
    "discontinuity_specjump_max_z": 0.0, "discontinuity_specjumps": 0.0,
    "discontinuity_hist_excess_var": 1.0, "discontinuity_hist_empty_frac": 0.0, "discontinuity_pcm16_lattice": 0.0,
    "discontinuity_n_seams": 0.0,
}


def _speech_span(fa: dict):
    """Sample range from the first to the last frame within 30 dB of the speech level (the utterance proper)."""
    loud = np.flatnonzero(~fa["silent"] & (fa["rms_db"] >= fa["speech_db"] - 30.0))
    if loud.size == 0:
        return 0, 0
    return int(loud[0] * fa["hop"]), int(loud[-1] * fa["hop"] + fa["win"])


def _zero_runs(x: np.ndarray, sr: int, fa: dict):
    """Exact digital-silence runs >= 5 ms, labelled lead / interior / trail relative to the speech span.

    A run that ends inside the first loud frame (or starts inside the last one) still belongs to the leading
    (trailing) silence, hence the one-frame tolerance.
    """
    on, off = _speech_span(fa)
    out = []
    for s, e in runs(np.abs(x) < ZERO_EPS, min_len=int(MIN_ZERO_RUN_S * sr)):
        region = "lead" if e <= on + fa["win"] else "trail" if s >= off - fa["win"] else "interior"
        out.append(dict(start_s=s / sr, end_s=e / sr, ms=(e - s) / sr * 1000, region=region, s=s, e=e))
    return out


def _dc_jumps(x: np.ndarray, sr: int):
    """Steps of the DC offset between adjacent 50 ms windows, relative to the windows' AC (mean-removed) RMS.

    The larger of the two AC levels is used: a speech window's own low-frequency content moves its mean, so a
    step is only unexplained when *both* windows are quiet relative to it (typically two pause windows).
    """
    n = int(DC_WIN_S * sr)
    k = len(x) // n
    if k < 2:
        return np.zeros(0), np.zeros(0), np.zeros(0)
    w = x[: k * n].reshape(k, n)
    mean = w.mean(axis=1)
    ac = np.sqrt(np.mean((w - mean[:, None]) ** 2, axis=1))
    step = np.abs(np.diff(mean))
    rel = step / (np.maximum(ac[:-1], ac[1:]) + 1 / 32768)
    t = (np.arange(1, k) * n) / sr
    return rel, step, t


def _clicks(x: np.ndarray, sr: int, exclude: np.ndarray):
    """Sample-level discontinuities: |2nd difference| far above the local scale, taken as the largest of the
    median |2nd difference| of the 5 ms block containing the sample and its two neighbours. A speech onset or
    plosive raises the scale of the following block and so is not flagged; an isolated click in a quiet
    stretch, or a cut / dropped sample, stands far above all three blocks."""
    d2 = np.abs(np.diff(x, n=2))
    blk = max(8, int(0.005 * sr))
    nb = len(d2) // blk
    if nb < 3:
        return [], 0.0
    med = np.median(d2[: nb * blk].reshape(nb, blk), axis=1)
    scale = np.maximum(ndimage.maximum_filter1d(med, size=3, mode="nearest"), CLICK_FLOOR)
    r = d2[: nb * blk] / (1.4826 * np.repeat(scale, blk))
    r[exclude[1: nb * blk + 1]] = 0.0            # d2[i] is centred on sample i+1
    hits = np.flatnonzero(r > CLICK_RATIO)
    groups = [g for g in np.split(hits, np.flatnonzero(np.diff(hits) > blk) + 1) if g.size] if hits.size else []
    clicks = [((g[np.argmax(r[g])] + 1) / sr, float(r[g].max())) for g in groups]
    return clicks, float(r.max()) if r.size else 0.0


def _histogram(x: np.ndarray):
    """Amplitude-histogram regularity on the 16-bit grid.

    Re-scaling already-quantised audio (digital gain, normalisation after quantisation) leaves a comb: some
    integer levels are never used (gain > 1) or used twice as often (gain < 1). Each level's count is compared
    with the mean of its two neighbours; for a smooth histogram with Poisson counts the normalised residual
    has variance ~1, a comb drives it far higher. Levels within +-16 LSB of zero are skipped because the
    histogram peak there is too sharp for a neighbour comparison.
    Returns (excess variance, fraction of unexpectedly empty levels, fraction of samples on the 16-bit grid).
    """
    q = x * 32768.0
    lattice = float(np.mean(np.abs(q - np.round(q)) < 1e-3))
    qi = np.round(q).astype(np.int64)
    nz = np.abs(qi[qi != 0])
    if nz.size < 1000:
        return 1.0, 0.0, lattice
    vmax = int(np.clip(np.percentile(nz, 90), 64, 4096))
    # histogram of levels -vmax-1 .. vmax+1; values beyond are dropped (not piled into the end bins, which
    # would make the outermost levels' neighbours meaningless)
    inside = np.abs(qi) <= vmax + 1
    h = np.bincount(qi[inside] + vmax + 1, minlength=2 * vmax + 3).astype(float)
    lvl = np.arange(-vmax - 1, vmax + 2)
    nb = 0.5 * (h[:-2] + h[2:])                   # neighbour mean for levels -vmax .. vmax
    c, lv = h[1:-1], lvl[1:-1]
    ok = (np.abs(lv) > 16) & (nb >= 20)
    if ok.sum() < 20:
        return 1.0, 0.0, lattice
    resid = (c[ok] - nb[ok]) / np.sqrt(1.5 * nb[ok])
    return float(np.var(resid)), float(np.mean(c[ok] == 0)), lattice


@expert("discontinuity", "splice", cost="cheap")
def discontinuity(ctx: Context) -> Evidence:
    """Splice and discontinuity detector: (1) runs of exact digital zeros >= 5 ms, split into leading, interior
    and trailing (interior zero gaps never occur in one natural recording); (2) isolated DC-offset steps between
    adjacent 50 ms windows or between consecutive pauses (plus the sub-audio drift of the background, a live-
    microphone trait); (3) background noise-floor change points between consecutive pauses; (4) sample-level
    clicks (second-difference outliers not explained by local signal energy) and abrupt spectral-envelope
    changes inside pauses (reported as background transients); (5) amplitude-histogram comb from
    re-quantisation. Suspected seam times are returned for the report overlay."""
    ev = Evidence("discontinuity", "splice")
    x, sr = mono(ctx), int(ctx.sr)
    fa = frame_analysis(ctx)
    feats = ev.features
    seams = []                                     # (time_s, seam type)

    if len(x) < int(0.1 * sr) or fa["silent"].all():
        ev.applicable = False
        ev.findings.append(Finding("Clip is empty or entirely digital silence; no continuity analysis possible.", 0, 0.0))
        return finalize(ev, DEFAULTS)

    # (1) digital-zero runs --------------------------------------------------------------------------
    zr = _zero_runs(x, sr, fa)
    lead = [r for r in zr if r["region"] == "lead"]
    trail = [r for r in zr if r["region"] == "trail"]
    inner = [r for r in zr if r["region"] == "interior"]
    feats.update(
        discontinuity_zero_lead_ms=sum(r["ms"] for r in lead),
        discontinuity_zero_trail_ms=sum(r["ms"] for r in trail),
        discontinuity_zero_interior_count=float(len(inner)),
        discontinuity_zero_interior_ms=sum(r["ms"] for r in inner),
        discontinuity_zero_interior_max_ms=max((r["ms"] for r in inner), default=0.0),
        discontinuity_zero_total_frac=sum(r["e"] - r["s"] for r in zr) / len(x),
    )
    for r in inner:
        seams += [(r["start_s"], "digital-silence gap start"), (r["end_s"], "digital-silence gap end")]
    ev.artifacts["zero_runs"] = [(round(r["start_s"], 4), round(r["ms"], 1), r["region"]) for r in zr]

    # samples next to zero runs or clipped runs are excluded from the click detector (known, not clicks)
    exclude = np.zeros(len(x), bool)
    guard = int(0.003 * sr)
    for r in zr:
        exclude[max(0, r["s"] - guard): r["e"] + guard] = True
    peak = float(np.max(np.abs(x)))
    for s, e in runs(np.abs(x) >= 0.999 * peak, min_len=3) if peak > 0 else []:
        exclude[max(0, s - guard): e + guard] = True

    # (2) DC offset and DC steps ---------------------------------------------------------------------
    feats["discontinuity_dc_offset_dbfs"] = float(20 * np.log10(max(abs(float(np.mean(x))), 1e-6)))
    rel, step, t_dc = _dc_jumps(x, sr)
    if rel.size:
        # boundaries touching a digital-zero run are already reported as zero runs
        near_zero = np.array([exclude[min(int(t * sr), len(x) - 1)] for t in t_dc])
        rel = np.where(near_zero, 0.0, rel)
        # Slow infrasonic background movement (air, handling, LF room noise) makes window means wander all the
        # time; a splice between recordings with different DC offsets is one isolated step.
        hit = (rel > DC_JUMP_REL) & (step > DC_JUMP_ABS) & (step > DC_JUMP_ISOLATION * np.median(step))
        feats["discontinuity_dc_jump_max_rel"] = float(rel.max())
        feats["discontinuity_dc_jumps"] = float(hit.sum())
        seams += [(float(t), "DC-offset step") for t in t_dc[hit]]

    # (3) noise-floor change points between consecutive pauses ---------------------------------------
    segs, band_pow, times = fa["long_pauses"], fa["band_pow"], fa["times"]
    if len(segs) >= 2:
        lv = np.array([level for _, _, level in segs])
        d = np.abs(np.diff(lv))
        feats["discontinuity_floor_change_max_db"] = float(d.max())
        hit = np.flatnonzero(d >= FLOOR_CHANGE_DB)
        feats["discontinuity_floor_changes"] = float(hit.size)
        # the change happened somewhere in the speech between the two pauses; mark the midpoint
        seams += [(float((times[segs[i][1] - 1] + times[segs[i + 1][0]]) / 2), "noise-floor change") for i in hit]
        # DC offset of the background in consecutive long pauses: a step hidden under speech (where the
        # adjacent-window test cannot see it) still shows up as pauses sitting at different DC levels.
        hop, win = fa["hop"], fa["win"]
        pm, pa = [], []
        for s, e, _ in segs:
            seg = x[s * hop: (e - 1) * hop + win]
            pm.append(float(seg.mean()))
            pa.append(float(seg.std()))
        pm, pa = np.array(pm), np.array(pa)
        dstep = np.abs(np.diff(pm))
        drel = dstep / (np.maximum(pa[:-1], pa[1:]) + 1 / 32768)
        feats["discontinuity_pause_dc_step_rel"] = float(drel.max())
        hit = np.flatnonzero((drel > PAUSE_DC_REL) & (dstep > DC_JUMP_ABS))
        feats["discontinuity_dc_jumps"] += float(hit.size)
        seams += [(float((times[segs[i][1] - 1] + times[segs[i + 1][0]]) / 2), "DC-offset step") for i in hit]

    # (4a) sample-level clicks -------------------------------------------------------------------------
    clicks, rmax = _clicks(x, sr, exclude)
    feats["discontinuity_click_max_ratio"] = rmax
    feats["discontinuity_clicks"] = float(len(clicks))
    seams += [(t, "click") for t, _ in sorted(clicks, key=lambda c: -c[1])[:5]]

    # (4b) abrupt spectral-envelope change inside pauses (frames 20 ms apart, both pause frames). On the test
    # set these fire more often on real clips than on synthetic ones: they are mostly short natural events
    # (breaths, lip/mouth noise, handling). They are therefore reported as background transients, not seams;
    # a real seam in the background shows up as a lasting level change (3) instead.
    pause = fa["pause"]
    idx = np.flatnonzero(pause[:-2] & pause[2:] & ~fa["silent"][1:-1])
    if idx.size >= 10:
        bdb = 10 * np.log10(band_pow)
        dist = np.sqrt(np.mean((bdb[idx + 2] - bdb[idx]) ** 2, axis=1))
        med = np.median(dist)
        mad = 1.4826 * np.median(np.abs(dist - med)) + 0.5
        z = (dist - med) / mad
        hit = (z > SPECJUMP_Z) & (dist > SPECJUMP_MIN_DB)
        feats["discontinuity_specjump_max_z"] = float(z.max())
        feats["discontinuity_specjumps"] = float(hit.sum())
        ev.artifacts["background_events_s"] = [round(float(times[i + 1]), 3) for i in idx[hit]]

    # (5) amplitude histogram --------------------------------------------------------------------------
    xv, empty, lattice = _histogram(x)
    feats.update(discontinuity_hist_excess_var=xv, discontinuity_hist_empty_frac=empty,
                 discontinuity_pcm16_lattice=lattice)

    # merge seams and publish for the report overlay ----------------------------------------------------
    seams.sort()
    merged = []
    for t, kind in seams:
        if merged and t - merged[-1][0] < SEAM_MERGE_S:
            if kind not in merged[-1][1]:
                merged[-1] = (merged[-1][0], merged[-1][1] + " + " + kind)
        else:
            merged.append((t, kind))
    ev.artifacts["seams_s"] = [round(float(t), 4) for t, _ in merged]
    ev.artifacts["seam_types"] = [k for _, k in merged]
    feats["discontinuity_n_seams"] = float(len(merged))

    # findings (strongest first; finalize() keeps 4) ----------------------------------------------------
    if inner:
        longest = max(inner, key=lambda r: r["ms"])
        where = ", ".join(f"{r['start_s']:.2f} s ({r['ms']:.0f} ms)" for r in inner[:4])
        ev.findings.append(Finding(
            f"{len(inner)} stretch(es) of exact digital silence inside the utterance (at {where}; longest "
            f"{longest['ms']:.0f} ms). A single natural recording always carries some background noise between "
            f"words, so perfectly zero samples mid-speech mean the audio was generated, concatenated or edited "
            f"(e.g. digitally inserted pauses).", +1, min(0.6, 0.35 + 0.05 * len(inner))))
    if lead and feats["discontinuity_zero_lead_ms"] >= 5:
        ev.findings.append(Finding(
            f"The clip starts with {feats['discontinuity_zero_lead_ms']:.0f} ms of exact digital silence before the "
            f"speech. A live microphone produces background noise from the first sample; zero-padding at the start "
            f"is a common trait of speech-synthesis output (and of some editing tools).", +1, 0.35))
    if trail and feats["discontinuity_zero_trail_ms"] >= 5:
        ev.findings.append(Finding(
            f"The clip ends with {feats['discontinuity_zero_trail_ms']:.0f} ms of exact digital silence (padding "
            f"added after the recording). This is an editing/export trace rather than evidence of synthesis.", 0, 0.1))
    other = [(t, k) for t, k in merged if "digital-silence" not in k]
    if other:
        kinds = sorted({k for _, k in other})
        ev.findings.append(Finding(
            f"{len(other)} suspected seam(s) from waveform/background discontinuities ({'; '.join(kinds)}) at "
            f"{', '.join(f'{t:.2f} s' for t, _ in other[:5])}. Such breaks (an isolated DC step, a click, a lasting "
            f"change of the background level between pauses) arise where separately recorded or generated pieces "
            f"are joined; a background change can also come from a noise gate or denoiser.",
            +1, min(0.4, 0.15 + 0.05 * len(other))))
    if lattice > 0.99 and (xv > HIST_COMB_VAR or empty > 0.2):
        ev.findings.append(Finding(
            f"The amplitude histogram is comb-shaped ({empty * 100:.0f}% of expected 16-bit levels unused, excess "
            f"variance {xv:.1f}): the audio was digitally re-scaled after being quantised. This indicates "
            f"post-processing (gain/normalisation in an editor), not synthesis by itself.", 0, 0.15))
    drift = feats["discontinuity_dc_jump_max_rel"]
    if drift > DC_DRIFT_REL and not feats["discontinuity_dc_jumps"]:
        ev.findings.append(Finding(
            f"The quiet background carries slow sub-audio (below ~20 Hz) drift: the mean of adjacent 50 ms windows "
            f"wanders by up to {drift:.1f}x the background's own level. Live microphones in real rooms pick this up "
            f"(air movement, handling, building rumble); speech synthesizers rarely reproduce it.", -1, 0.1))
    if not zr and not other:
        ev.findings.append(Finding(
            "No digital-silence gaps, DC steps, clicks or abrupt background changes were found: no sign of "
            "splicing or padding.", -1, 0.1))
    n_ev = len(ev.artifacts.get("background_events_s", []))
    if n_ev:
        ev.findings.append(Finding(
            f"{n_ev} brief transient event(s) in the pauses (at {', '.join(f'{t:.2f} s' for t in ev.artifacts['background_events_s'][:4])}), "
            f"such as breaths, lip/mouth noise or handling; on the challenge data these occur more often in real "
            f"recordings than in synthetic ones.", -1, 0.05))
    return finalize(ev, DEFAULTS)
